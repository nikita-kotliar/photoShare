function slugFor(index, tags) {
  const base = (tags[0] || 'photo').replace(/[^a-z0-9]/gi, '') || 'photo';
  return `${base}-${String(index).padStart(2, '0')}x${(index * 7919).toString(36)}`;
}

export function createSeed(now = Date.now()) {
  const users = userSeeds.map(([username, name, role, hasAvatar, isActive = true], index) => ({
    id: index + 1,
    username,
    name,
    email: `${username}@example.com`,
    password: TEST_PASSWORD,
    role,
    isActive,
    avatarUrl: hasAvatar ? `/mock/avatars/user-${String(index + 1).padStart(2, '0')}.svg` : null,
    createdAt: new Date(now - (90 - index * 6) * DAY).toISOString(),
  }));

  const photos = photoSeeds.map(([authorId, description, tags], index) => {
    const created = new Date(now - (35 - index * 3) * DAY - index * 3600000).toISOString();
    return {
      id: index + 1,
      slug: slugFor(index + 1, ['photo']),
      url: `/mock/photos/photo-${String(index + 1).padStart(2, '0')}.svg`,
      description,
      tags,
      authorId,
      createdAt: created,
      updatedAt: created,
    };
  });

  const comments = commentSeeds.map(
    ([photoId, authorId, text, createdDaysAgo, editedDaysAgo], index) => ({
      id: index + 1,
      photoId,
      authorId,
      text,
      createdAt: new Date(now - createdDaysAgo * DAY - index * 60000).toISOString(),
      updatedAt: new Date(
        now - (editedDaysAgo ?? createdDaysAgo) * DAY - index * 60000,
      ).toISOString(),
    }),
  );

  const ratings = ratingSeeds.map(([photoId, userId, value], index) => ({
    id: index + 1,
    photoId,
    userId,
    value,
    createdAt: new Date(now - (10 - (index % 9)) * DAY).toISOString(),
  }));

  const links = [
    {
      id: 1,
      photoId: 1,
      transformations: { effect: 'sepia', crop: 'square' },
      createdAt: new Date(now - 5 * DAY).toISOString(),
    },
    {
      id: 2,
      photoId: 1,
      transformations: { effect: 'grayscale', angle: 90 },
      createdAt: new Date(now - 4 * DAY).toISOString(),
    },
  ];

  return { users, photos, comments, ratings, links };
}
